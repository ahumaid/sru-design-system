import { readFileSync, writeFileSync } from 'node:fs';

const sourcePath = 'src/styles/sru-theme.scss';
const outputPath = 'public/design-system/sru-tokens.css';
const tokenNames = [
    '--sru-font-family',
    '--sru-white',
    '--sru-purple',
    '--sru-purple-dark',
    '--sru-bg-primary',
    '--sru-surface-alt',
    '--sru-line',
    '--sru-ink',
    '--sru-muted',
    '--sru-on-dark-muted',
    '--sru-on-dark-border',
    '--sru-on-dark-divider',
    '--sru-on-dark-hover',
    '--sru-bg-dark',
    '--sru-bg-dark-secondary',
    '--sru-bg-dark-tertiary',
    '--bs-dark-bg-subtle',
];

const source = readFileSync(sourcePath, 'utf8');
const rootStart = source.indexOf(':root {');

if (rootStart === -1) {
    throw new Error(`Could not find the canonical :root token block in ${sourcePath}`);
}

let depth = 0;
let rootEnd = -1;

for (let index = source.indexOf('{', rootStart); index < source.length; index += 1) {
    if (source[index] === '{') depth += 1;
    if (source[index] === '}') depth -= 1;
    if (depth === 0) {
        rootEnd = index;
        break;
    }
}

const findBlockEnd = (start) => {
    let blockDepth = 0;
    for (let index = source.indexOf('{', start); index < source.length; index += 1) {
        if (source[index] === '{') blockDepth += 1;
        if (source[index] === '}') blockDepth -= 1;
        if (blockDepth === 0) return index;
    }
    return -1;
};

const extractDeclarations = (block) => new Map(
    [...block.matchAll(/^\s*((?:--sru|--bs)-[\w-]+):\s*(.+);\s*$/gm)]
        .map(([, name, value]) => [name, value]),
);

const rootBlock = source.slice(rootStart, rootEnd);
const declarations = extractDeclarations(rootBlock);
const missingTokens = tokenNames.filter((name) => !declarations.has(name));

if (missingTokens.length > 0) {
    throw new Error(`Missing canonical SRU token(s): ${missingTokens.join(', ')}`);
}

const darkStart = source.indexOf(":root[data-bs-theme='dark'] {");
const darkEnd = darkStart === -1 ? -1 : findBlockEnd(darkStart);
const darkDeclarations = darkEnd === -1
    ? new Map()
    : extractDeclarations(source.slice(darkStart, darkEnd));

const output = [
    '/* Generated from src/styles/sru-theme.scss. Do not edit this file directly. */',
    ':root {',
    ...tokenNames.map((name) => `    ${name}: ${declarations.get(name)};`),
    '}',
    ...(darkDeclarations.size > 0
        ? [
            '',
            ":root[data-bs-theme='dark'] {",
            ...tokenNames
                .filter((name) => darkDeclarations.has(name))
                .map((name) => `    ${name}: ${darkDeclarations.get(name)};`),
            '}',
        ]
        : []),
    '',
].join('\n');

writeFileSync(outputPath, output);
